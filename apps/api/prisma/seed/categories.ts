/**
 * `W3-T01` — the category tree, as data.
 *
 * Two family roots and twenty leaves. This is the vocabulary a provider picks from, the list a
 * client searches by, and the column `W3-T08` reads as fact — so it ships as **curated seed data**
 * rather than behind an admin CRUD. §9 of the spec argues the difference: an endpoint that creates
 * a category at runtime makes `BD-07`'s legal answer editable by whoever holds an admin session,
 * which is the opposite of a legal boundary.
 *
 * **Not `localOnly`**, deliberately. `auth.demo-users` carries that flag because its rows have a
 * published password; nothing here is a credential or a person. A preview database should hold the
 * real taxonomy — it is the vocabulary the product is written in, not demo content — and since
 * `W3-T01` that is also what lets a preview deploy answer `GET /api/categories` with real rows
 * instead of the MSW handler this ticket deleted.
 *
 * Spec: `docs/specs/S3/W3-T01-category-tree.md` §3.5, §3.6, §8.3, §8.4.
 */
import { type Seeder } from './types.js';

/**
 * A node of the tree.
 *
 * `parent` is a **slug**, not an id: the roots' ids are generated by Postgres, and a seed constant
 * that had to know them would be a constant that cannot be read. `run` resolves them.
 */
export interface TaxonomyNode {
  /**
   * Fixed only for the four rows adopted from `demo-providers.ts` (§3.6). Everything else lets the
   * database generate one — `MEM-2026-09-18-1` fixes ids so a uuid in a screenshot still resolves,
   * and only the demo world has screenshots.
   */
  readonly id?: string;
  readonly slug: string;
  readonly nameEs: string;
  readonly nameEn: string;
  /** Per sibling set, 1..n. The curated order — the trades a marketplace wants first (§3.8). */
  readonly position: number;
  /**
   * **Declared on every row, never defaulted.** The operator ruled on 2026-09-18 (`BD-07`): five
   * `true`, fifteen `false`. A row whose answer had not arrived would not ship with `false`; it
   * would ship with the deferral spelled out, or not at all (§3.5).
   *
   * It marks a trade whose claim is **checkable and worth badging** — not one that hides unverified
   * providers. An electrician with no documents is listed, searchable and bookable; what they lack
   * is the badge (§3.5.2).
   */
  readonly requiresLicence: boolean;
  /** `null` for a family root. */
  readonly parent: string | null;
}

/** The four uuids `demo-providers.ts` created and this seeder adopts, so its links survive (§3.6). */
