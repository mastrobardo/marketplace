export const categoryTaxonomy: Seeder = {
  id: 'categories.taxonomy',
  description:
    'Two family roots and twenty trades (W3-T01) — the vocabulary a provider picks from, with ' +
    "BD-07's five gated trades in requires_licence",

  /**
   * **`upsert`, not `create`.** `run.ts` runs each seeder once per database via its ledger, so a
   * plain `create` would be correct nearly always — and then collide with `category_slug_key` the
   * first time somebody re-runs this after a partial failure, or edits the taxonomy and wants the
   * rows brought up to date. The `update` half makes this a sync rather than an insert: change a
   * name or a position here, re-run, and the table follows (AC16).
   */
  async run({ db }) {
    const ids = new Map<string, string>();

    for (const node of TAXONOMY) {
      // Roots come first in `TAXONOMY`, so a parent is always already in the map. A slug that is
      // not names itself rather than writing `null` and quietly reparenting a trade to the root.
      let parentId: string | null = null;
      if (node.parent !== null) {
        const found = ids.get(node.parent);
        if (found === undefined) {
          throw new Error(`Category "${node.slug}" names a parent "${node.parent}" that is not seeded yet`);
        }
        parentId = found;
      }

      const fields = {
        nameEs: node.nameEs,
        nameEn: node.nameEn,
        parentId,
        requiresLicence: node.requiresLicence,
        position: node.position,
      };

      const row = await db.category.upsert({
        where: { slug: node.slug },
        create: { ...(node.id === undefined ? {} : { id: node.id }), slug: node.slug, ...fields, isActive: true },
        /**
         * **`isActive` is absent here, and that is the point.** It is the retirement mechanism
         * (§3.8, AC12): an operator sets it `false` to take a trade off the wire without touching
         * the `provider_category` rows that record who did it. If the update half carried
         * `isActive: true`, the next re-run of this seeder — after a typo fix, say — would put every
         * retired trade back on the public list, silently. Retirement is data, not taxonomy.
         */
        update: fields,
        select: { id: true },
      });

      ids.set(node.slug, row.id);
    }
  },
};
